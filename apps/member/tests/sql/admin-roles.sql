begin;
create temp table admin_role_results(check_name text,passed boolean);
create function pg_temp.change_member_role(actor uuid,target uuid,new_role text) returns void language plpgsql as $$
declare payload jsonb;
begin
 perform set_config('request.jwt.claim.sub',actor::text,true);
 select jsonb_build_object('user_id',target,'role',new_role,'role_version',coalesce(r.version,0),'reason','Role fixture — transaction rollback only','confirmation',u.email) into payload from auth.users u left join private_website_lab.member_roles r on r.user_id=u.id where u.id=target;
 perform public.website_manage_members('set_role',payload);
end $$;
create function pg_temp.must_deny(statement text) returns void language plpgsql as $$
declare denied boolean:=false;
begin
 begin execute statement;exception when insufficient_privilege then denied:=true;end;
 if not denied then raise exception 'Expected permission denial: %',statement;end if;
end $$;
do $$
declare a uuid;b uuid;c uuid;aid uuid:=gen_random_uuid();other_id uuid:=gen_random_uuid();doc jsonb;result jsonb;v bigint;denied boolean;
begin
 perform set_config('request.jwt.claims','{"role":"authenticated"}',true);
 select user_id into a from private_website_lab.member_roles where role='full_admin' and private_website_lab.permitted(user_id,'roles') limit 1;
 select id into b from auth.users where email_confirmed_at is not null and private_website_lab.account_allowed(id) and private_website_lab.assigned_role(id)='member' order by id limit 1;
 select id into c from auth.users where id<>b and email_confirmed_at is not null and private_website_lab.account_allowed(id) and private_website_lab.assigned_role(id)='member' order by id limit 1;
 if a is null or b is null or c is null then raise exception 'Approved admin and two disposable staging fixtures required';end if;
 perform set_config('request.jwt.claim.sub',b::text,true);
 if private_website_lab.permitted(b,'news') or private_website_lab.permitted(b,'operations') then raise exception 'Member has admin permission';end if;
 perform pg_temp.must_deny($q$select public.website_manage_members('list')$q$);
 perform pg_temp.must_deny($q$select public.website_news_admin('list')$q$);
 insert into admin_role_results values('member cannot reach administrative tools',true);
 perform pg_temp.change_member_role(a,b,'writer');
 perform set_config('request.jwt.claim.sub',b::text,true);
 result:=public.website_admin_capabilities();
 if (result->>'news')::boolean is not true or (result->>'publish')::boolean or (result->>'operations')::boolean or (result->>'roles')::boolean then raise exception 'Wrong writer capabilities';end if;
 doc:=jsonb_build_object('title','A staging role fixture','excerpt','A sufficiently long summary for a safe publication fixture.','body',repeat('A safe fixture paragraph for permission verification. ',5),'author','Fixture writer','category','Data','format','news','cover_url','','cover_alt','','source_name','','source_url','');
 result:=public.website_news_admin('save',jsonb_build_object('id',aid,'revision',0,'slug','role-fixture-'||aid,'document',doc));
 if result->>'created_by'<>b::text or (result->>'can_publish')::boolean then raise exception 'Writer save/author wrong';end if;
 perform public.website_news_admin('get',jsonb_build_object('id',aid));
 perform pg_temp.must_deny(format($q$select public.website_news_admin('publish','%s'::jsonb)$q$,jsonb_build_object('id',aid,'revision',1)));
 perform pg_temp.must_deny($q$select public.website_lab('list')$q$);
 perform pg_temp.must_deny($q$select public.website_contact_admin('list')$q$);
 perform pg_temp.must_deny($q$select public.website_opportunity_admin('list')$q$);
 insert into admin_role_results values('writer can save own draft but cannot publish or reach operations',true);
 perform pg_temp.change_member_role(a,c,'editor');
 perform set_config('request.jwt.claim.sub',c::text,true);
 perform public.website_news_admin('get',jsonb_build_object('id',aid));
 result:=public.website_news_admin('publish',jsonb_build_object('id',aid,'revision',1));
 if result->>'status'<>'published' then raise exception 'Editor could not publish';end if;
 perform public.website_news_admin('save',jsonb_build_object('id',other_id,'revision',0,'slug','role-fixture-'||other_id,'document',doc));
 perform pg_temp.must_deny($q$select public.website_manage_members('list')$q$);
 perform pg_temp.must_deny($q$select public.website_lab('list')$q$);
 perform pg_temp.must_deny($q$select public.website_opportunity_admin('list')$q$);
 insert into admin_role_results values('editor can review and publish another author but not reach operations',true);
 perform set_config('request.jwt.claim.sub',b::text,true);
 result:=public.website_news_admin('list');
 if exists(select 1 from jsonb_array_elements(result->'items') x where x->>'id' in (aid::text,other_id::text)) then raise exception 'Writer sees published or other author private article';end if;
 denied:=false;begin perform public.website_news_admin('get',jsonb_build_object('id',other_id));exception when no_data_found then denied:=true;end;
 if not denied then raise exception 'Writer fetched another author draft';end if;
 perform pg_temp.must_deny(format($q$select public.website_news_admin('save','%s'::jsonb)$q$,jsonb_build_object('id',other_id,'revision',1,'slug','role-fixture-'||other_id,'document',doc)));
 perform pg_temp.must_deny(format($q$select public.website_news_admin('save','%s'::jsonb)$q$,jsonb_build_object('id',aid,'revision',2,'slug','role-fixture-'||aid,'document',doc)));
 insert into admin_role_results values('writer ownership and previously published article restrictions enforced',true);
 perform pg_temp.change_member_role(a,b,'operations_admin');
 perform set_config('request.jwt.claim.sub',b::text,true);
 perform public.website_manage_members('list');perform public.website_lab('list');perform public.website_contact_admin('list');
 perform pg_temp.must_deny($q$select public.website_news_admin('list')$q$);
 perform pg_temp.must_deny($q$select public.website_opportunity_admin('list')$q$);
 perform pg_temp.must_deny(format($q$select public.website_manage_members('set_role','%s'::jsonb)$q$,jsonb_build_object('user_id',c,'role','full_admin','role_version',1,'reason','Fixture forbidden escalation','confirmation','fixture@example.invalid')));
 insert into admin_role_results values('operations admin manages operations but cannot grant roles or publish',true);
 perform set_config('request.jwt.claim.sub',a::text,true);
 v:=coalesce((select version from private_website_lab.member_roles where user_id=b),0);
 perform pg_temp.change_member_role(a,b,'member');
 denied:=false;begin perform public.website_manage_members('set_role',jsonb_build_object('user_id',b,'role','writer','role_version',v,'reason','Fixture stale role write','confirmation',(select email from auth.users where id=b)));exception when raise_exception then denied:=true;end;
 if not denied then raise exception 'Stale role update accepted';end if;
 perform set_config('request.jwt.claim.sub',b::text,true);
 perform pg_temp.must_deny($q$select public.website_manage_members('list')$q$);
 if private_website_lab.permitted(b,'operations') then raise exception 'Retained identity kept revoked role';end if;
 insert into admin_role_results values('role demotion immediate for retained identity; stale edits rejected',true);
 denied:=false;begin perform pg_temp.change_member_role(a,a,'member');exception when raise_exception then denied:=true;end;
 if not denied then raise exception 'Last Full admin removed';end if;
 perform pg_temp.change_member_role(a,b,'full_admin');
 perform pg_temp.change_member_role(a,a,'operations_admin');
 perform pg_temp.must_deny(format($q$select public.website_manage_members('set_role','%s'::jsonb)$q$,jsonb_build_object('user_id',c,'role','full_admin','role_version',1,'reason','Fixture former admin escalation','confirmation','fixture@example.invalid')));
 denied:=false;begin perform pg_temp.change_member_role(b,b,'member');exception when raise_exception then denied:=true;end;
 if not denied then raise exception 'Remaining Full admin removed';end if;
 perform pg_temp.change_member_role(b,a,'full_admin');
 perform set_config('request.jwt.claim.sub',a::text,true);
 result:=public.website_manage_members('detail',jsonb_build_object('user_id',b));
 if jsonb_array_length(result->'role_audit')<4 or (result->>'can_manage_roles')::boolean is not true then raise exception 'Role history or Full admin controls missing';end if;
 insert into admin_role_results values('last Full admin protected; controlled handover and role audit recorded',true);
 perform set_config('request.jwt.claim.sub',c::text,true);
 execute 'set local role authenticated';
 perform pg_temp.must_deny(format($q$insert into private_website_lab.member_roles(user_id,role) values('%s','full_admin') on conflict(user_id) do update set role='full_admin'$q$,c));
 execute 'reset role';
 insert into admin_role_results values('direct role-table escalation denied',true);
end $$;
select * from admin_role_results;
rollback;
